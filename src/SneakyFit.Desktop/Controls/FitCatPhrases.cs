    public static string Insight(FitInsight insight)
    {
        var templates = insight.Kind switch
        {
            FitInsightKind.FoodStreak => FoodStreaks,
            FitInsightKind.ActivityStreak => ActivityStreaks,
            FitInsightKind.WeightProgress => WeightProgress,
            _ => throw new ArgumentOutOfRangeException(nameof(insight))
        };
        return string.Format(Russian, Pick(insight.Kind.ToString(), templates),
            insight.Days, Days(insight.Days), insight.Value.ToString("0.#", Russian));
    }

    private static string Days(int count)
    {
        var lastTwo = count % 100;
        if (lastTwo is >= 11 and <= 14) return "дней";
        return (count % 10) switch { 1 => "день", 2 or 3 or 4 => "дня", _ => "дней" };
    }

    private static string Pick(string group, string[] phrases)
    {
        lock (Previous)
        {
            int index;
            if (Previous.TryGetValue(group, out var previous) && phrases.Length > 1)
            {
                index = Random.Shared.Next(phrases.Length - 1);
                if (index >= previous) index++;
            }
            else index = Random.Shared.Next(phrases.Length);
            Previous[group] = index;
            return phrases[index];
        }
    }

